// ponytail: Expo's iOS build scripts use unquoted paths, so a project path with a space
// ("Personal Projects") breaks the local iOS build. Quote them here; EAS cloud paths have
// no spaces. Remove once Expo ships the fix upstream.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const RN_XCODE = "require('path').dirname(require.resolve('react-native/package.json')) + '/scripts/react-native-xcode.sh'";

const patches = [
  [
    'node_modules/expo-constants/ios/EXConstants.podspec',
    'bash -l -c \\"#{env_vars}$PODS_TARGET_SRCROOT/../scripts/get-app-config-ios.sh\\"',
    'bash -l -c \\"#{env_vars}\'$PODS_TARGET_SRCROOT/../scripts/get-app-config-ios.sh\'\\"',
  ],
  [
    'node_modules/expo-constants/scripts/get-app-config-ios.sh',
    'PROJECT_DIR_BASENAME=$(basename $PROJECT_DIR)',
    'PROJECT_DIR_BASENAME=$(basename "$PROJECT_DIR")',
  ],
  [
    'node_modules/expo-updates/ios/EXUpdates.podspec',
    'bash -l -c "$PODS_TARGET_SRCROOT/../scripts/create-updates-resources-ios.sh"',
    'bash -l -c "\\\'$PODS_TARGET_SRCROOT/../scripts/create-updates-resources-ios.sh\\\'"',
  ],
  // The generated Xcode project runs the bundle script through unquoted backticks.
  // ios/ is gitignored and regenerated by prebuild, so re-run this after `expo prebuild`.
  [
    'ios/TaktHealth.xcodeproj/project.pbxproj',
    '\\n\\n`\\"$NODE_BINARY\\" --print \\"' + RN_XCODE + '\\"`\\n\\n',
    '\\n\\n\\"$(\\"$NODE_BINARY\\" --print \\"' + RN_XCODE + '\\")\\"\\n\\n',
  ],
];

for (const [file, from, to] of patches) {
  const target = path.join(root, file);
  if (!fs.existsSync(target)) continue;
  const text = fs.readFileSync(target, 'utf8');
  if (text.includes(to)) continue;
  if (!text.includes(from)) {
    console.warn(`fix-ios-paths: pattern not found in ${file}; the package may have changed`);
    continue;
  }
  fs.writeFileSync(target, text.replace(from, to));
  console.log(`fix-ios-paths: patched ${file}`);
}

// Xcode 27 sandboxes build scripts by default, which blocks Node from writing main.jsbundle
// in Release archives ("Sandbox: node deny file-write-create"). Local only, like the path fixes.
const pbxproj = path.join(root, 'ios/TaktHealth.xcodeproj/project.pbxproj');
if (fs.existsSync(pbxproj)) {
  const text = fs.readFileSync(pbxproj, 'utf8');
  if (text.includes('ENABLE_USER_SCRIPT_SANDBOXING = YES;')) {
    fs.writeFileSync(pbxproj, text.split('ENABLE_USER_SCRIPT_SANDBOXING = YES;').join('ENABLE_USER_SCRIPT_SANDBOXING = NO;'));
    console.log('fix-ios-paths: disabled user script sandboxing in the Xcode project');
  }
}
